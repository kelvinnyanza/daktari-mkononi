// Brand asset generator — the ONE place the logo geometry lives.
// Writes the SVG sources (assets/brand/*.svg) and every raster the app ships:
// in-app mark (@1x/2x/3x), app icon, Android adaptive icon (foreground +
// monochrome), splash image and web favicon. React Native has no built-in SVG
// renderer (react-native-svg would be a new native module), so the app uses PNGs.
// Dev-only: @resvg/resvg-js is a devDependency and never reaches the bundle.
// Usage: pnpm --filter @daktari/mobile brand:assets
import { Resvg } from '@resvg/resvg-js';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const brand = path.join(root, 'assets', 'brand');

const TEAL = '#0F7366';
const MINT = '#8FD9C6';
const SPEAKER = '#A9DED4';
const HAND = 'M24 56 C 25 82, 40 95, 60 95 C 77 95, 91 88, 99 72';

/** Phone + cross + cupped hand, drawn on a 120×120 canvas. `gap` = colour of the cut-out around the hand. */
function markShapes(gap) {
  return [
    `<rect x="40" y="16" width="40" height="76" rx="11" fill="#FFFFFF"/>`,
    `<rect x="53" y="22" width="14" height="3.5" rx="1.75" fill="${SPEAKER}"/>`,
    `<rect x="55" y="36" width="10" height="30" rx="3" fill="${TEAL}"/>`,
    `<rect x="45" y="46" width="30" height="10" rx="3" fill="${TEAL}"/>`,
    `<path d="${HAND}" fill="none" stroke="${gap}" stroke-width="17" stroke-linecap="round"/>`,
    `<path d="${HAND}" fill="none" stroke="${MINT}" stroke-width="9" stroke-linecap="round"/>`,
  ].join('\n  ');
}

const svg = (body, size = 120) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">\n  ${body}\n</svg>\n`;

/** The mark centred and scaled inside a larger transparent canvas (adaptive-icon safe zone, splash). */
const inset = (body, scale) => `<g transform="translate(${60 - 60 * scale} ${60 - 60 * scale}) scale(${scale})">\n  ${body}\n  </g>`;

const SOURCES = {
  // Rounded tile — the in-app mark and logo lockup.
  'logo-mark.svg': svg(`<rect width="120" height="120" rx="32" fill="${TEAL}"/>\n  ${markShapes(TEAL)}`),
  // Square, full-bleed — iOS/stores apply their own corner mask.
  'app-icon.svg': svg(`<rect width="120" height="120" fill="${TEAL}"/>\n  ${inset(markShapes(TEAL), 0.86)}`),
  // Android adaptive foreground: transparent, artwork inside the central 66% safe zone
  // (background colour is set in app.json).
  'adaptive-foreground.svg': svg(inset(markShapes(TEAL), 0.6)),
  // Android 13+ themed icon: one-colour silhouette; cut-outs are true holes (mask).
  'adaptive-monochrome.svg': svg(
    `<defs><mask id="m">
    <rect width="120" height="120" fill="#000"/>
    ${inset(
      [
        `<rect x="40" y="16" width="40" height="76" rx="11" fill="#FFF"/>`,
        `<rect x="55" y="36" width="10" height="30" rx="3" fill="#000"/>`,
        `<rect x="45" y="46" width="30" height="10" rx="3" fill="#000"/>`,
        `<path d="${HAND}" fill="none" stroke="#000" stroke-width="17" stroke-linecap="round"/>`,
        `<path d="${HAND}" fill="none" stroke="#FFF" stroke-width="9" stroke-linecap="round"/>`,
      ].join('\n    '),
      0.6,
    )}
  </mask></defs>
  <rect width="120" height="120" fill="#FFFFFF" mask="url(#m)"/>`,
  ),
  // Splash: the rounded tile on transparent; background colour comes from the splash plugin.
  'splash-icon.svg': svg(inset(`<rect width="120" height="120" rx="32" fill="${TEAL}"/>\n  ${markShapes(TEAL)}`, 1)),
};

/** [svg source, output png, width px] */
const RASTERS = [
  ['logo-mark.svg', 'logo-mark.png', 96],
  ['logo-mark.svg', 'logo-mark@2x.png', 192],
  ['logo-mark.svg', 'logo-mark@3x.png', 288],
  ['app-icon.svg', 'app-icon.png', 1024],
  ['adaptive-foreground.svg', 'adaptive-foreground.png', 1024],
  ['adaptive-monochrome.svg', 'adaptive-monochrome.png', 1024],
  ['splash-icon.svg', 'splash-icon.png', 1024],
  ['logo-mark.svg', 'favicon.png', 48],
];

const HEADER = `<!--
  Daktari Mkononi logo (original). GENERATED by scripts/brand-assets.mjs —
  edit the geometry there, then run pnpm --filter @daktari/mobile brand:assets.
  A white phone held in a mint, cupped hand, with a teal health cross on its
  screen: "a doctor in your hand" (daktari mkononi).
-->
`;

fs.mkdirSync(brand, { recursive: true });
for (const [name, content] of Object.entries(SOURCES)) {
  fs.writeFileSync(path.join(brand, name), HEADER + content);
}
for (const [source, out, width] of RASTERS) {
  const png = new Resvg(SOURCES[source], { fitTo: { mode: 'width', value: width } }).render().asPng();
  fs.writeFileSync(path.join(brand, out), png);
  console.log(`${out} (${width}px, ${png.length} bytes)`);
}
