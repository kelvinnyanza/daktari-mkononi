#!/usr/bin/env node
/**
 * Create a working `.env` for local development, once.
 *
 * Every secret is generated with crypto.randomBytes rather than shipped as a
 * placeholder: a committed example secret is the kind of thing that survives
 * into staging. Provider keys are left blank on purpose — blank selects the
 * fake adapter in dev, and the production guard refuses to boot on blanks.
 *
 * Idempotent: an existing .env is never modified or overwritten.
 */
import { randomBytes } from 'node:crypto';
import { access, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEV_DB, PG_PASSWORD, PG_PORT, PG_USER } from './db.mjs';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENV_PATH = path.join(REPO_ROOT, '.env');

const exists = async (target) => {
  try {
    await access(target);
    return true;
  } catch {
    return false;
  }
};

/** URL-safe secret of `bytes` entropy — used for JWT/pepper/signing secrets. */
const secret = (bytes) => randomBytes(bytes).toString('base64url');
/** AES-256-GCM key: exactly 32 bytes as 64 hex chars (see @daktari/encryption). */
const hexKey = (bytes) => randomBytes(bytes).toString('hex');

const DEV_DATABASE_URL =
  `postgresql://${PG_USER}:${PG_PASSWORD}@localhost:${PG_PORT}/${DEV_DB}`;

function buildEnvFile() {
  return `# Daktari Mkononi — local development environment.
# Generated by \`pnpm dev:setup\` on ${new Date().toISOString()}.
# Secrets below are random and local to this machine. NOT for staging or
# production: generate fresh ones there and keep them in a secret manager.

NODE_ENV=development
LOG_LEVEL=debug

# Public URLs. The web portal calls the API directly, and CORS is pinned to
# APP_URL, so these two must match where the servers actually listen.
APP_URL=http://localhost:3000
API_URL=http://localhost:4000

# Where the BROWSER reaches the API. Same value as API_URL for local work;
# NEXT_PUBLIC_* is inlined into the client bundle at build time.
NEXT_PUBLIC_API_URL=http://localhost:4000

# Local PostgreSQL managed by \`pnpm db:start\` (binaries in .local/pg16).
DATABASE_URL=${DEV_DATABASE_URL}

# Redis is OPTIONAL in dev: unset means in-memory rate limiting and
# /health/ready reports redis "skipped". Required in production.
# REDIS_URL=redis://localhost:6379

# ── Secrets (generated) ──────────────────────────────────────────────────────
JWT_ACCESS_SECRET=${secret(48)}
JWT_REFRESH_SECRET=${secret(48)}
JWT_ACCESS_EXPIRY=15m
JWT_REFRESH_EXPIRY=30d

# AES-256-GCM key for PHI at rest — exactly 32 bytes as hex.
# Changing this makes every previously encrypted row undecryptable.
ENCRYPTION_KEY=${hexKey(32)}

# HMAC pepper for OTP hashing, and the signing key for file-download tokens.
OTP_PEPPER=${secret(32)}
FILE_SIGNING_SECRET=${secret(32)}

# ── External providers (blank = local fake) ──────────────────────────────────
# SMS unset      -> ConsoleSms: OTP codes PRINT TO THE API CONSOLE.
#                   That is how you log in locally.
# AzamPay unset  -> FakePayments; use the dev payment-flip endpoint
#                   POST /api/v1/dev/payments/:appointmentId/complete
# Daily.co unset -> FakeVideo: rooms and tokens are stubs, no real call.
# AI key unset   -> AI screening returns 503 AI_NOT_CONFIGURED. It is NOT
#                   faked implicitly: a stub that answers medical triage
#                   plausibly is more dangerous than one that is plainly
#                   unavailable. Set the key for AI_PROVIDER (anthropic |
#                   openai), or AI_PROVIDER=fake for canned "[JARIBIO]"
#                   replies (dev only). AI_MODEL blank = provider default.
AI_PROVIDER=anthropic
ANTHROPIC_API_KEY=
OPENAI_API_KEY=
AI_MODEL=

SMS_API_KEY=
AZAMPAY_APP_NAME=
AZAMPAY_CLIENT_ID=
AZAMPAY_CLIENT_SECRET=
AZAMPAY_WEBHOOK_SECRET=
DAILY_CO_API_KEY=

AWS_ACCESS_KEY_ID=
AWS_SECRET_ACCESS_KEY=

# Local document storage root (LocalDiskStorage); S3 takes over in production.
STORAGE_ROOT=.storage
`;
}

async function main() {
  if (await exists(ENV_PATH)) {
    // Never touch an existing .env: it may hold real provider keys the
    // developer pasted in, and silently regenerating secrets would make every
    // encrypted row in their database unreadable.
    console.log('.env already exists — leaving it untouched.');
    const current = await readFile(ENV_PATH, 'utf8');
    const missing = ['DATABASE_URL', 'JWT_ACCESS_SECRET', 'ENCRYPTION_KEY', 'OTP_PEPPER',
      'FILE_SIGNING_SECRET', 'JWT_REFRESH_SECRET']
      .filter((key) => !new RegExp(`^${key}=.+`, 'm').test(current));
    if (missing.length > 0) {
      console.log(`\n⚠ It is missing values for: ${missing.join(', ')}`);
      console.log('  Add them, or delete .env and re-run `pnpm dev:setup`.');
      process.exitCode = 1;
      return;
    }
    console.log('Run `pnpm dev:doctor` to check your setup.');
    return;
  }

  await writeFile(ENV_PATH, buildEnvFile(), 'utf8');
  console.log(`Created ${path.relative(REPO_ROOT, ENV_PATH)} with freshly generated secrets.`);
  console.log('\nNext:');
  console.log('  pnpm db:start    # start local PostgreSQL, create databases');
  console.log('  pnpm db:push     # apply the Prisma schema');
  console.log('  pnpm db:seed     # seed Tanzanian test data');
  console.log('  pnpm dev:doctor  # verify everything above');
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
